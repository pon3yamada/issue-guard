#!/bin/bash
# ============================================================
# validate-issue.sh のケース表 — 合格させるべき本文と落とすべき本文を並べて、判定を目撃する
#
# なぜ要るか: 行頭の `#173 の件で…` を見出しと誤認して、課題も成功の定義もある Issue に
#   needs-goal を付けていた。門番の判定を直すたびに手で確かめる
#   のではなく、「通すもの」と「落とすもの」の両方を表にしておく。
#
# 使い方: validate-issue-cases.sh [検査する validate-issue.sh のパス]
#   省略時は同じディレクトリの validate-issue.sh。同じスクリプトのコピー
#   （create-issue スキル側）もパスを渡せば同じ表で検査できる。
# ★件数はここに書かない。末尾の合計行だけを正とする。
#
# 終了コード: 0 = 全ケース期待どおり / 1 = 1 つでも外れた
# ============================================================
set -u

V="${1:-$(cd "$(dirname "$0")" && pwd)/validate-issue.sh}"
[ -f "$V" ] || { echo "検査対象がありません: $V"; exit 1; }

TMPD=$(mktemp -d)
trap 'rm -rf "$TMPD"' EXIT

N=0; NG=0
# case <期待する終了コード> <説明>   本文は標準入力から
case_() {
  local want="$1" desc="$2" got
  N=$((N + 1))
  cat > "$TMPD/body.md"
  bash "$V" "$TMPD/body.md" > "$TMPD/out" 2>&1; got=$?
  if [ "$got" = "$want" ]; then
    printf '  [x] %s\n' "$desc"
  else
    NG=$((NG + 1))
    printf '  [ ] %s（期待 rc=%s / 実際 rc=%s）\n' "$desc" "$want" "$got"
    sed 's/^/      /' "$TMPD/out"
  fi
  return 0
}

echo "validate-issue ケース表: $V"

# --- 合格すべきもの ---
case_ 0 "型どおりの本文は合格" <<'EOF'
## ゴール

### 課題
ラベルの付け忘れが多い。

### 成功の定義
- 付け忘れが 0 件になる
EOF

case_ 0 "節の中身が行頭 #番号 の行だけでも合格" <<'EOF'
## ゴール

### 課題
#173 の件で、Issue Guard が needs-goal を誤って付けた。

### 成功の定義
#173 と同じ本文が合格する。
EOF

case_ 0 "行頭 #番号 の行の後ろの行も節の中身として数える" <<'EOF'
## ゴール

### 課題
#12 と #13 の続き。
<!-- ここはコメント -->

### 成功の定義
#12 を閉じる
- 実内容の行
EOF

case_ 0 "行頭のハッシュタグ（# の直後が空白でない）も見出しではない" <<'EOF'
## ゴール

### 課題
#needs-goal が誤って付いた。

### 成功の定義
#needs-goal が付かない。
EOF

case_ 0 "CRLF の本文でも合格" < <(printf '## ゴール\r\n\r\n### 課題\r\n#173 の件\r\n\r\n### 成功の定義\r\n合格する\r\n')

# --- 落とすべきもの（従来どおり） ---
case_ 1 "### 課題 が無ければ不合格" <<'EOF'
## ゴール

### 成功の定義
#173 と同じ本文が合格する。
EOF

case_ 1 "### 成功の定義 が無ければ不合格" <<'EOF'
## ゴール

### 課題
#173 の件。
EOF

case_ 1 "## ゴール が無ければ不合格" <<'EOF'
### 課題
困っている。

### 成功の定義
直る。
EOF

case_ 1 "コメントしか無い節は不合格" <<'EOF'
## ゴール

### 課題
<!-- 何に困っているか
複数行のコメント -->

### 成功の定義
- 直る
EOF

case_ 1 "次の見出し（# + 空白）までで節が切れる — 空の課題は不合格" <<'EOF'
## ゴール

### 課題
# 大見出しのつもり
本文

### 成功の定義
- 直る
EOF

case_ 1 "次の見出しが #### でも節が切れる — 空の成功の定義は不合格" <<'EOF'
## ゴール

### 課題
困っている。

### 成功の定義
#### 補足
本文
EOF

case_ 1 "# だけの行（空の見出し）でも節が切れる" <<'EOF'
## ゴール

### 課題
#
本文

### 成功の定義
- 直る
EOF

if [ "$NG" -eq 0 ]; then
  echo "validate-issue ケース表: 合格（${N} ケース）"
  exit 0
fi
echo "validate-issue ケース表: 不合格（${NG}/${N} ケース）"
exit 1
